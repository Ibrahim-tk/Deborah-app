import styles from './SocialButton.module.css';

export interface SocialButtonProps extends ButtonHTMLAttributes<HTMLButtonElement> {
  provider: 'apple' | 'google';
}

const LABEL = { apple: 'Continue with Apple', google: 'Continue with Google' } as const;

export function SocialButton({ provider, className, children, ...rest }: SocialButtonProps) {
  return (
    <button type="button" className={cx(styles.root, styles[provider], className)} {...rest}>
      {provider === 'apple' ? <AppleMark /> : <GoogleMark />}
      <span>{children ?? LABEL[provider]}</span>
    </button>
  );
}

